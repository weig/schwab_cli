# ---- client (manual paste) flow ----------------------------------------------


def test_client_extracts_code_from_pasted_url():
    cfg = _cfg_client()

    captured = {}

    def fake_open(url):
        from urllib.parse import parse_qs, urlparse
        captured["state"] = parse_qs(urlparse(url).query)["state"][0]
        return True

    def fake_prompt(label):
        # Echo back the state that was generated, with a code.
        return f"https://127.0.0.1:8443/?code=PASTED_CODE&state={captured['state']}"

    with patch("schwab_cli.auth_flows.webbrowser.open", side_effect=fake_open), \
         patch("schwab_cli.auth_flows.typer.prompt", side_effect=fake_prompt):
        code = get_code(cfg)
    assert code == "PASTED_CODE"


